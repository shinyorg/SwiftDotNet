using System.Runtime.InteropServices;
using System.Text;
using SwiftDotNet.Hosting;

namespace SwiftDotNet.Watch;

/// <summary>Function pointers the Swift host registers at launch. Mirrors <c>SwiftDotNetWatchCallbacks</c> in swiftdotnet_watch.h.</summary>
[StructLayout(LayoutKind.Sequential)]
public unsafe struct WatchNativeCallbacks
{
    /// <summary>(patchJson) → apply a TreeDiffer patch; the Swift side copies the string.</summary>
    public delegate* unmanaged<byte*, void> Render;
    public delegate* unmanaged<void> RequestDrain;
    public delegate* unmanaged<int, byte*, void> Log;
    /// <summary>(operation, argsJson) → malloc'd UTF-8 JSON result or null; the managed side frees it.</summary>
    public delegate* unmanaged<byte*, byte*, byte*> Call;
}

/// <summary>
/// The C ABI the SwiftUI watch app calls (see <c>sdk/swift/swiftdotnet_watch.h</c>). NativeAOT exports these
/// because the app project lists this assembly as an <c>UnmanagedEntryPointsAssembly</c>. The one export
/// that lives in the app assembly is <c>swiftdotnet_watch_bootstrap</c> — generated by the SDK, because only
/// the app knows how to build its <see cref="SwiftDotNetApp"/> — and it calls <see cref="Bootstrap"/>.
/// </summary>
public static unsafe class WatchExports
{
    static WatchNativeCallbacks s_callbacks;

    /// <summary>Called by the generated <c>swiftdotnet_watch_bootstrap</c> export, on the main thread.</summary>
    public static void Bootstrap(Func<SwiftDotNetApp> createApp)
    {
        ArgumentNullException.ThrowIfNull(createApp);
        try
        {
            WatchHost.Start(createApp(), new CallbackPlatform());
        }
        catch (Exception ex)
        {
            WatchHost.Log(WatchLogLevel.Error, "SwiftDotNet watch bootstrap failed: " + ex);
        }
    }

    [UnmanagedCallersOnly(EntryPoint = "swiftdotnet_watch_register_callbacks")]
    static void RegisterCallbacks(WatchNativeCallbacks* native) => s_callbacks = *native;

    [UnmanagedCallersOnly(EntryPoint = "swiftdotnet_watch_event")]
    static void Event(byte* id, byte* value)
    {
        try
        {
            if (FromNative(id) is { } nodeId)
                WatchHost.DispatchEvent(nodeId, FromNative(value));
        }
        catch (Exception ex) { WatchHost.Log(WatchLogLevel.Error, ex.ToString()); }
    }

    [UnmanagedCallersOnly(EntryPoint = "swiftdotnet_watch_native_event")]
    static void NativeEvent(byte* name, byte* json)
    {
        try
        {
            if (FromNative(name) is { } n)
                WatchHost.RaiseNativeEvent(n, FromNative(json));
        }
        catch (Exception ex) { WatchHost.Log(WatchLogLevel.Error, ex.ToString()); }
    }

    /// <summary>0 = active, 1 = inactive, 2 = background.</summary>
    [UnmanagedCallersOnly(EntryPoint = "swiftdotnet_watch_phase")]
    static void Phase(int phase)
    {
        try { WatchHost.SetPhase((WatchAppPhase)phase); }
        catch (Exception ex) { WatchHost.Log(WatchLogLevel.Error, ex.ToString()); }
    }

    [UnmanagedCallersOnly(EntryPoint = "swiftdotnet_watch_drain")]
    static void Drain()
    {
        try { WatchHost.Drain(); }
        catch (Exception ex) { WatchHost.Log(WatchLogLevel.Error, ex.ToString()); }
    }

    static byte* ToNative(string s)
    {
        var bytes = Encoding.UTF8.GetBytes(s);
        var ptr = (byte*)NativeMemory.Alloc((nuint)bytes.Length + 1);
        bytes.CopyTo(new Span<byte>(ptr, bytes.Length));
        ptr[bytes.Length] = 0;
        return ptr;
    }

    static string? FromNative(byte* ptr) => ptr == null ? null : Marshal.PtrToStringUTF8((nint)ptr);

    sealed class CallbackPlatform : IWatchPlatform
    {
        public void Render(string patchJson)
        {
            if (s_callbacks.Render == null)
                return;
            var json = ToNative(patchJson);
            try { s_callbacks.Render(json); }
            finally { NativeMemory.Free(json); }
        }

        public void RequestMainThreadDrain()
        {
            if (s_callbacks.RequestDrain != null)
                s_callbacks.RequestDrain();
        }

        public void Log(WatchLogLevel level, string message)
        {
            if (s_callbacks.Log == null)
            {
                Console.WriteLine($"[{level}] {message}");
                return;
            }
            var msg = ToNative(message);
            try { s_callbacks.Log((int)level, msg); }
            finally { NativeMemory.Free(msg); }
        }

        public string? Call(string operation, string argsJson)
        {
            if (s_callbacks.Call == null)
                throw new InvalidOperationException("The watch host did not register a native call handler.");
            var op = ToNative(operation);
            var args = ToNative(argsJson);
            try
            {
                var result = s_callbacks.Call(op, args);
                if (result == null)
                    return null;
                var s = FromNative(result);
                NativeMemory.Free(result); // strdup'd by Swift
                return s;
            }
            finally
            {
                NativeMemory.Free(op);
                NativeMemory.Free(args);
            }
        }
    }
}
